-- altz: Alt-Z hides the whole UI (chat and strip); cards must hide within two captures and come
-- back when the UI does.
local E = E2E.Start({ name = "altz" })
local ids = E.Filler()
E.Wait(2)
E.Click(ids.party)
E.Wait(1.2)
E.Click(ids.long)
E.Wait(3)
E.Mark("Alt-Z on")
E.AltZ(true)
E.Wait(3)
E.Mark("Alt-Z off")
E.AltZ(false)
E.Wait(3)
E.Mark("short Alt-Z")
E.AltZ(true)
E.Wait(0.8)
E.AltZ(false)
E.Wait(3)
E.Finish(2)
