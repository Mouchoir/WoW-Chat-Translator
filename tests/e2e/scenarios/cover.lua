-- cover: a game tooltip over part of a plate. The Helper's mask must leave the tooltip alone.
local E = E2E.Start({ name = "cover" })
local ids = E.Filler()
E.Wait(2)
E.Click(ids.trade)
E.Wait(1.2)
E.Click(ids.long)
E.Wait(2.5)
E.Mark("tooltip over the right half of a plate")
local c1 = E.Cover({ line = ids.trade, row = 0, fx = { 0.5, 1.0 }, pad = { 10, 60, 30, 0 } })
E.Wait(4)
E.Uncover(c1)
E.Wait(2)
E.Mark("tooltip over the middle of two rows")
local c2 = E.Cover({ line = ids.long, row = 1, fx = { 0.3, 0.6 }, pad = { 6, 0, 26, 0 } })
E.Wait(4)
E.Uncover(c2)
E.Wait(2)
E.Finish(2)
