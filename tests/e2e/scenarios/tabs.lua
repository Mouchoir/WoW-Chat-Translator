-- tabs: a second chat window shows the same lines (each frame has its own copy of the reserved
-- rows), then a tab switch hides the first one, then back.
local E = E2E.Start({ name = "tabs" })
local ids = E.Filler()
E.Wait(2)
E.Click(ids.guild)
E.Wait(1.2)
E.Click(ids.fr)
E.Wait(2.5)
E.Mark("second chat window")
E.ShowFrame(ChatFrame3, { 470, 60, 430, 330 })
E.Wait(4)
E.Mark("tab switch: only the second window")
E.HideFrame(ChatFrame1)
E.Wait(4)
E.Mark("tab switch back")
E.ShowFrame(ChatFrame1)
E.HideFrame(ChatFrame3)
E.Wait(4)
E.Finish(2)
