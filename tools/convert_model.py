"""Convert a Mozilla Firefox Translations model into a LoadOnDemand WoW addon.

Input (models/<pair>/): model.<xx><yy>.intgemm.alphas.bin (Marian intgemm8), vocab.<xx><yy>.spm
(SentencePiece) and lex.50.50.<xx><yy>.s2t.bin (binary lexical shortlist).
Output (<out>/TranslateProbe_<xx><yy>/): a TOC and Lua files that only assign data into the
global table TranslateProbeModels["<xx>-<yy>"]:
  - int8 weight matrices (stored q + 128, row = one output, row-major) as base64 strings,
    decoded in game with C_EncodingUtil.DecodeBase64; the embedding in blocks of 256 rows;
  - biases, layer-norm vectors and the output bias as number tables;
  - per-matrix scales (qB) and activation multipliers (alpha);
  - the SentencePiece pieces, scores and types, plus the single-character part of the
    normalization map that matters for chat text;
  - the shortlist as base64 uint32 offsets and uint16 target ids.

Usage: python -I -X utf8 tools/convert_model.py <models_dir> <pair> <out_dir>
"""
import base64
import os
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import marian_ref as mr  # noqa: E402

ROWS_PER_BLOCK = 256           # embedding rows per string (64 KB at D = 256)
FILE_LIMIT = 3 * 1024 * 1024   # bytes of Lua source per data file
LICENSES = {
    'default': 'Mozilla Firefox Translations model, MPL-2.0 (github.com/mozilla/firefox-translations-models)',
    'de-en': 'Bergamot project student model distributed by Mozilla, CC-BY-SA-4.0 (github.com/browsermt/students)',
    'es-en': 'Bergamot project student model distributed by Mozilla, CC-BY-SA-4.0 (github.com/browsermt/students)',
}


def lua_bytes(b):
    """Lua double-quoted literal for raw bytes (UTF-8 kept as is)."""
    out = bytearray(b'"')
    for c in b:
        if c == 0x22:
            out += b'\\"'
        elif c == 0x5C:
            out += b'\\\\'
        elif c < 0x20 or c == 0x7F:
            out += b'\\%03d' % c
        else:
            out.append(c)
    out += b'"'
    return bytes(out)


def lua_num(v):
    if isinstance(v, int):
        return str(v)
    r = repr(float(v))
    assert r not in ('inf', '-inf', 'nan'), r
    return r


def lua_table(values):
    return '{' + ','.join(lua_num(v) for v in values) + '}'


def b64(data):
    return base64.b64encode(data).decode('ascii')


class Writer:
    """Splits generated Lua into files of at most FILE_LIMIT bytes."""

    def __init__(self, folder, header):
        self.folder, self.header, self.files, self.buf = folder, header, [], bytearray()

    def add(self, chunk):
        if isinstance(chunk, str):
            chunk = chunk.encode('utf-8')
        if self.buf and len(self.buf) + len(chunk) > FILE_LIMIT:
            self.flush()
        self.buf += chunk + b'\n'

    def flush(self):
        if not self.buf:
            return
        name = 'Data%02d.lua' % (len(self.files) + 1)
        with open(os.path.join(self.folder, name), 'wb') as f:
            f.write(self.header + bytes(self.buf))
        self.files.append(name)
        self.buf = bytearray()


def int8_as_bytes(q):
    """Signed int8 values -> bytes holding q + 128 (1..255 for the -127..127 range)."""
    return bytes((v + 128) & 0xFF for v in q)


def scalar(items, name):
    it = items[name]
    if it[0] == mr.T_INTGEMM8:            # 2022 models pack Wemb_QuantMultA like a matrix
        q, qm = mr.item_intgemm8(it)
        return q[0] / qm
    return mr.item_floats(it)[0]


def main():
    models_dir, pair, out_dir = sys.argv[1], sys.argv[2], sys.argv[3]
    code = pair.replace('-', '')
    src = os.path.join(models_dir, pair)
    with open(os.path.join(src, 'model.%s.intgemm.alphas.bin' % code), 'rb') as f:
        items = mr.read_marian_bin(f.read())
    with open(os.path.join(src, 'vocab.%s.spm' % code), 'rb') as f:
        spm = mr.SentencePiece(f.read())
    with open(os.path.join(src, 'lex.50.50.%s.s2t.bin' % code), 'rb') as f:
        lex = mr.read_shortlist_bin(f.read())

    model = mr.Model(items)
    V, D = model.V, model.D
    FF = items['encoder_l1_ffn_W1'][1][1]
    folder = os.path.join(out_dir, 'TranslateProbe_' + code)
    os.makedirs(folder, exist_ok=True)
    for old in os.listdir(folder):
        os.remove(os.path.join(folder, old))

    header = ('-- Generated by tools/convert_model.py from the %s model. Do not edit.\n'
              '-- %s\nlocal M = TranslateProbeModels["%s"]\nlocal B, F = M.blobs, M.floats\n'
              % (pair, LICENSES.get(pair, LICENSES['default']), pair)).encode('utf-8')
    w = Writer(folder, header)

    # Matrices: every *_W* except the embedding, in a fixed order the engine walks.
    matrices = []
    names = [n for n in items if items[n][0] == mr.T_INTGEMM8 and n not in ('Wemb', 'Wemb_QuantMultA')]
    for name in sorted(names):
        n_in, n_out = items[name][1]
        q, qB = mr.item_intgemm8(items[name])
        alpha = mr.item_floats(items[name + '_QuantMultA'])[0]
        matrices.append((name, n_out, n_in, qB, alpha))
        w.add(b'B["' + name.encode() + b'"] = "' + b64(int8_as_bytes(q)).encode() + b'"')

    qE, qmE = mr.item_intgemm8(items['Wemb'])
    blocks = 0
    for start in range(0, V, ROWS_PER_BLOCK):
        rows = min(ROWS_PER_BLOCK, V - start)
        part = qE[start * D:(start + rows) * D]
        blocks += 1
        w.add('B["Wemb#%d"] = "%s"' % (blocks, b64(int8_as_bytes(part))))

    floats = [n for n in items if items[n][0] == mr.T_FLOAT32 and not n.endswith('_QuantMultA')]
    for name in sorted(floats):
        w.add('F["%s"] = %s' % (name, lua_table(mr.item_floats(items[name]))))

    w2o, lists = lex['w2o'], lex['lists']
    assert max(lists) < 65536 and w2o[-1] < 2 ** 32
    w.add('B["lex_offsets"] = "%s"' % b64(struct.pack('<%dI' % len(w2o), *w2o)))
    w.add('B["lex_ids"] = "%s"' % b64(struct.pack('<%dH' % len(lists), *lists)))

    # Vocabulary: pieces as raw UTF-8 literals, scores, types.
    pieces = b'M.pieces = {' + b','.join(lua_bytes(p) for p, _, _ in spm.pieces) + b'}'
    w.add(pieces)
    w.add('M.scores = ' + lua_table([s for _, s, _ in spm.pieces]))
    w.add('M.types = ' + lua_table([t for _, _, t in spm.pieces]))
    # Single-character normalization entries outside CJK ranges (chat text in Latin, Cyrillic,
    # punctuation, full-width forms). Longer keys and CJK compatibility forms are left to
    # C_Intl.Normalize in game.
    small = []
    for k, v in spm.cmap.items():
        try:
            ks = k.decode('utf-8')
        except UnicodeDecodeError:
            continue
        if len(ks) == 1 and (ord(ks) < 0x3000 or 0xFF00 <= ord(ks) <= 0xFFEF):
            small.append((k, v))
    small.sort()
    w.add(b'M.charmap = {' + b','.join(b'[' + lua_bytes(k) + b']=' + lua_bytes(v) for k, v in small) + b'}')
    w.flush()

    meta = ['-- Generated by tools/convert_model.py from the %s model. Do not edit.' % pair,
            '-- %s' % LICENSES.get(pair, LICENSES['default']),
            'TranslateProbeModels = TranslateProbeModels or {}',
            'local M = { pair = "%s", blobs = {}, floats = {} }' % pair,
            'TranslateProbeModels["%s"] = M' % pair,
            'M.config = { D = %d, H = %d, FF = %d, V = %d, enc = %d, dec = %d, eos = %d, unk = %d, '
            'rowsPerBlock = %d, embBlocks = %d, wembQB = %s, outAlpha = %s, firstNum = %d, '
            'byteFallback = %s, addDummyPrefix = %s, removeExtraWhitespaces = %s, escapeWhitespaces = %s, '
            'minScore = %s, maxScore = %s }' % (
                D, model.H, FF, V, model.enc_depth, model.dec_depth, spm.eos_id, spm.unk_id,
                ROWS_PER_BLOCK, blocks, lua_num(qmE), lua_num(scalar(items, 'Wemb_QuantMultA')), lex['firstNum'],
                'true' if spm.trainer.get('byte_fallback') else 'false',
                'true' if spm.norm['add_dummy_prefix'] else 'false',
                'true' if spm.norm['remove_extra_whitespaces'] else 'false',
                'true' if spm.norm['escape_whitespaces'] else 'false',
                lua_num(spm.min_score), lua_num(spm.max_score)),
            'M.matrices = {']
    for name, rows, cols, qB, alpha in matrices:
        meta.append('    { name = "%s", rows = %d, cols = %d, qB = %s, alpha = %s },'
                    % (name, rows, cols, lua_num(qB), lua_num(alpha)))
    meta.append('}')
    with open(os.path.join(folder, 'Meta.lua'), 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(meta) + '\n')

    toc = ['## Interface: 16001',
           '## Title: TranslateProbe model %s' % pair,
           '## Notes: Translation model data for TranslateProbe (%s). %s' % (pair, LICENSES.get(pair, LICENSES['default'])),
           '## LoadOnDemand: 1',
           '## Dependencies: TranslateProbe',
           '',
           'Meta.lua'] + w.files
    with open(os.path.join(folder, 'TranslateProbe_%s.toc' % code), 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(toc) + '\n')

    total = sum(os.path.getsize(os.path.join(folder, n)) for n in os.listdir(folder))
    print('%s: %d matrices, %d embedding blocks, %d floats tables, %d charmap entries, %d files, %.1f MB'
          % (pair, len(matrices), blocks, len(floats), len(small), len(w.files) + 2, total / 1048576))


if __name__ == '__main__':
    main()
