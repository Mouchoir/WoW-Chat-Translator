"""Build the character-trigram language profiles used by Lang.lua to tell Latin-script languages
apart. Training text: the client's localized UI strings (GlobalStrings/<locale>.lua from an
in-game dump), which are game vocabulary in each language. Only trigram statistics are kept.

Usage: python -I -X utf8 tools/make_langid.py <GlobalStrings_dir> <out LangData.lua>
"""
import collections
import math
import os
import re
import sys

LOCALES = {'en': 'enUS', 'de': 'deDE', 'fr': 'frFR', 'es': 'esES', 'it': 'itIT', 'pt': 'ptBR'}
TOP = 1000   # trigrams kept per language

LINE = re.compile(r'^[A-Za-z0-9_]+ = "(.*)";\s*$')
CODES = re.compile(r'\|c[0-9a-fA-F]{8}|\|r|\|T.*?\|t|\|A.*?\|a|\|H.*?\|h|\|n|\|4.*?;|%[-\d.$]*[a-zA-Z]|\\n')
NOT_LETTER = re.compile(r"[^a-zà-öø-ÿœ']+")


def words(text):
    text = CODES.sub(' ', text).lower()
    return [w for w in NOT_LETTER.sub(' ', text).split() if w.strip("'")]


def trigrams(word):
    padded = ' ' + word + ' '
    return [padded[i:i + 3] for i in range(len(padded) - 2)]


def lua_str(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def main():
    src, out = sys.argv[1], sys.argv[2]
    profiles = {}
    for lang, locale in LOCALES.items():
        counts = collections.Counter()
        with open(os.path.join(src, locale + '.lua'), encoding='utf-8') as f:
            for line in f:
                m = LINE.match(line)
                if m:
                    for w in words(m.group(1)):
                        counts.update(trigrams(w))
        total = sum(counts.values())
        top = counts.most_common(TOP)
        floor = math.log(top[-1][1] / total) - 1.0
        profiles[lang] = ({g: math.log(c / total) for g, c in top}, floor)
        print('%s: %d trigrams seen, kept %d, floor %.2f' % (lang, len(counts), len(top), floor))

    lines = ['-- Generated by tools/make_langid.py from the client\'s localized UI strings. Do not edit.',
             '-- Log-probabilities of the most common character trigrams per language (words padded with spaces).',
             'local _, ns = ...',
             'ns.LangData = { floor = {}, trigrams = {} }']
    for lang, (table, floor) in profiles.items():
        lines.append('ns.LangData.floor.%s = %.3f' % (lang, floor))
        items = ','.join('[%s]=%.3f' % (lua_str(g), v) for g, v in sorted(table.items()))
        lines.append('ns.LangData.trigrams.%s = {%s}' % (lang, items))
    with open(out, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines) + '\n')


if __name__ == '__main__':
    main()
